-- Setup ALC (Automata, Languages & Computation) Exam System
-- Table 1: Student Verification Table (3rd Year CSE)
-- Table 2: Results Table

-- Drop existing tables if they exist
DROP TABLE IF EXISTS "3rdcsealcresults" CASCADE;
DROP TABLE IF EXISTS "3rdcsealc" CASCADE;

-- Create Student Verification Table
CREATE TABLE "3rdcsealc" (
    id SERIAL PRIMARY KEY,
    roll_number VARCHAR(20) UNIQUE NOT NULL,
    unique_code VARCHAR(20) NOT NULL DEFAULT 'alc771',
    is_active BOOLEAN DEFAULT TRUE,
    verified_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Create Results Table
CREATE TABLE "3rdcsealcresults" (
    id SERIAL PRIMARY KEY,
    roll_number VARCHAR(20) NOT NULL,
    correct_answers INTEGER NOT NULL,
    wrong_answers INTEGER NOT NULL,
    total_questions INTEGER NOT NULL DEFAULT 10,
    marks DECIMAL(5,2) NOT NULL,
    percentage DECIMAL(5,2) NOT NULL,
    user_answers JSONB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (roll_number) REFERENCES "3rdcsealc"(roll_number) ON DELETE CASCADE
);

